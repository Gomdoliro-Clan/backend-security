CREATE TABLE organization (id uuid PRIMARY KEY, name varchar(120) NOT NULL, currency varchar(3) NOT NULL);
CREATE TABLE app_user (
  id uuid PRIMARY KEY, organization_id uuid NOT NULL REFERENCES organization, email varchar(200) NOT NULL UNIQUE,
  display_name varchar(120) NOT NULL, password_hash varchar(100) NOT NULL,
  role varchar(20) NOT NULL CHECK (role IN ('READER','ANALYST','BUYER','MANAGER')), active boolean NOT NULL DEFAULT true
);
CREATE TABLE access_token (token_hash varchar(64) PRIMARY KEY, user_id uuid NOT NULL REFERENCES app_user, expires_at timestamptz NOT NULL);
CREATE INDEX access_token_expiry ON access_token(expires_at);
CREATE TABLE supplier (
  id uuid PRIMARY KEY, organization_id uuid NOT NULL REFERENCES organization, name varchar(120) NOT NULL,
  contact_email varchar(200) NOT NULL, category varchar(80) NOT NULL, status varchar(20) NOT NULL
);
CREATE INDEX supplier_org ON supplier(organization_id);
CREATE TABLE catalog_item (
  id uuid PRIMARY KEY, organization_id uuid NOT NULL REFERENCES organization, sku varchar(40) NOT NULL,
  name varchar(120) NOT NULL, unit_price numeric(16,2) NOT NULL CHECK(unit_price>=0), stock integer NOT NULL CHECK(stock>=0),
  UNIQUE(organization_id,sku)
);
CREATE TABLE purchase_order (
  id uuid PRIMARY KEY, organization_id uuid NOT NULL REFERENCES organization, supplier_id uuid NOT NULL REFERENCES supplier,
  created_by uuid NOT NULL REFERENCES app_user, approved_by uuid REFERENCES app_user, title varchar(160) NOT NULL,
  department varchar(60) NOT NULL, amount numeric(16,2) NOT NULL CHECK(amount>0),
  status varchar(20) NOT NULL CHECK(status IN ('SUBMITTED','APPROVED','CANCELLED')), created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX purchase_org ON purchase_order(organization_id,created_at DESC);
CREATE TABLE invoice (
  id uuid PRIMARY KEY, organization_id uuid NOT NULL REFERENCES organization, number varchar(50) NOT NULL,
  department varchar(60) NOT NULL, total numeric(16,2) NOT NULL CHECK(total>0), status varchar(20) NOT NULL,
  issued_on date NOT NULL, memo text NOT NULL DEFAULT '', UNIQUE(organization_id,number)
);
CREATE INDEX invoice_org ON invoice(organization_id,issued_on DESC);
CREATE TABLE document (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organization_id uuid NOT NULL REFERENCES organization,
  title varchar(160) NOT NULL, kind varchar(30) NOT NULL, body text NOT NULL, archived boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX document_org ON document(organization_id);
CREATE TABLE audit_event (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, organization_id uuid NOT NULL REFERENCES organization,
  actor_id uuid NOT NULL REFERENCES app_user, action varchar(60) NOT NULL, resource_id uuid NOT NULL, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX audit_org ON audit_event(organization_id,created_at DESC);
